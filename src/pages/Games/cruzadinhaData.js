export function emptyGrid(fill = '') {
  return Array.from({ length: GRID_SIZE }, () => Array.from({ length: GRID_SIZE }, () => fill))
}

export function emptyBoolGrid() {
  return Array.from({ length: GRID_SIZE }, () => Array.from({ length: GRID_SIZE }, () => false))
}

export function emptyIndexGrid() {
  return Array.from({ length: GRID_SIZE }, () =>
    Array.from({ length: GRID_SIZE }, () => []),
  )
}

/** Monta a estrutura lógica da grade a partir das palavras. */
export function buildGrid(words = CRUZADINHA_WORDS) {
  const correctLetters = emptyGrid('')
  const cellIsPartOfWord = emptyBoolGrid()
  const cellToWordIndices = emptyIndexGrid()
  const wordEntries = []
  let totalCells = 0

  words.forEach((item, wordIdx) => {
    const { word, start, direction } = item
    const [row, col] = start
    const positions = []

    for (let i = 0; i < word.length; i++) {
      const currentRow = direction === 'horizontal' ? row : row + i
      const currentCol = direction === 'horizontal' ? col + i : col

      if (currentRow >= GRID_SIZE || currentCol >= GRID_SIZE) {
        console.error(`Palavra "${word}" não cabe na posição [${row},${col}]`)
        return
      }

      correctLetters[currentRow][currentCol] = word[i]
      if (!cellIsPartOfWord[currentRow][currentCol]) {
        cellIsPartOfWord[currentRow][currentCol] = true
        totalCells++
      }
      positions.push({ row: currentRow, col: currentCol })
      cellToWordIndices[currentRow][currentCol].push(wordIdx)
    }

    wordEntries.push({ word, positions, direction })
  })

  const positionMarkers = {}
  let wordIndex = 1
  wordEntries.forEach((entry) => {
    const first = entry.positions[0]
    positionMarkers[`${first.row},${first.col}`] = wordIndex++
  })

  return {
    correctLetters,
    cellIsPartOfWord,
    cellToWordIndices,
    wordEntries,
    totalCells,
    positionMarkers,
  }
}

export function countCompleted(userAnswers, correctLetters, cellIsPartOfWord) {
  let completed = 0
  for (let r = 0; r < GRID_SIZE; r++) {
    for (let c = 0; c < GRID_SIZE; c++) {
      if (!cellIsPartOfWord[r][c]) continue
      const val = userAnswers[r][c] || ''
      if (val !== '' && val === correctLetters[r][c]) completed++
    }
  }
  return completed
}

export function isWordComplete(entry, userAnswers, correctLetters) {
  return entry.positions.every((pos) => {
    const val = userAnswers[pos.row][pos.col] || ''
    return val === correctLetters[pos.row][pos.col]
  })
}

export function formatTime(seconds) {
  const mins = String(Math.floor(seconds / 60)).padStart(2, '0')
  const secs = String(seconds % 60).padStart(2, '0')
  return `${mins}:${secs}`
}
